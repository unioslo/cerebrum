"""
Generate a courses tree for LDAP.

This script generates a supplementary ldap tree to the generic org ldap tree.
It's part of a three step process, where this script takes care of the first
two steps:

1. Course data in LDAP
----------------------
This script generates an LDAP tree (typically "cn=course,dc=<org>,dc=no") with
basic course information.  Each course object is assigned a unique,
reproducible URN.  There are two types of course objects:

- ``uioEduOffering``, to represent course units (undervisningsenheter).
- ``uioEduSection``, to represent course activities (undervisningsaktiviteter).

2. Map people to course objects
-------------------------------
This script generates a (pickle) cache file for mapping account owners
(person-id) to a list of ``<role>@<urn>`` strings.  Roles are typically:

  - Learner (students)
  - Instructor (course lecturers and group instructors)

3. Include roles in org-tree
----------------------------
An optional mixin (:class:`Cerebrum.modules.no.OrgLDIF.OrgLdifCourseMixin`)
reads the cache file and adds course participation data to each org person.
This is typically represented as a multivalued attribute, with the
``<role>@<urn>`` strings from the cache as values.
"""
