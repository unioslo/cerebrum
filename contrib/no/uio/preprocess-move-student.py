class _InvalidRequest(Exception):
    pass


def _get_account_by_id(db, entity_id):
    obj = Factory.get("Account")(db)
    obj.find(int(entity_id))
    return obj


def _get_disk_by_id(db, entity_id):
    obj = Factory.get("Disk")(db)
    obj.find(int(entity_id))
    return obj


def _get_owner_fnr(account):
    """ Get fnr of account owner. """
    if account.owner_type != account.const.entity_person:
        return None
    pe = Factory.get("Person")(account._db)
    pe.find(int(account.owner_id))
    fnr_results = list(
        row['external_id']
        for row in pe.get_external_id(
            id_type=int(pe.const.externalid_fodselsnr),
            source_system=int(pe.const.system_fs)
        )
    )
    if not fnr_results:
        return None
    return fnr_results[0]


def _get_memberships(account):
    """ Get account membership group ids. """
    gr = Factory.get("Group")(account._db)
    return set(
        int(row["group_id"])
        for row in gr.search(member_id=int(account.entity_id),
                             indirect_members=False)
    )


class DiskCache(object):
    """ Build a cache of target disks for *move student* requests. """

    def __init__(self, db, autostud, disk_spread):
        self._db = db
        self._autostud = autostud
        self._account_cache = {}
        self._disk_cache = {}
        self._fnr_to_accounts = {}

        self.disk_spread = disk_spread

        # Target disk for account (account-id -> (homedir-id, new-disk-id)):
        self.account_to_disk = {}

        # account-ids that cant't be moved:
        self.ignore_accounts = set()

        # New disk quotas for homedirs (homedir-id -> new-quota):
        self.disk_quotas = {}

    def get_account(self, account_id):
        """ Look up and cache an account. """
        if account_id not in self._account_cache:
            try:
                account = _get_account_by_id(self._db, account_id)
            except Errors.NotFoundError:
                account = None
            self._account_cache[account_id] = account
        return self._account_cache[account_id]

    def get_disk(self, disk_id):
        """ Look up and cache a disk. """
        if disk_id not in self._disk_cache:
            try:
                obj = _get_disk_by_id(self._db, disk_id)
            except Errors.NotFoundError:
                obj = None
            self._disk_cache[disk_id] = obj
        return self._disk_cache[disk_id]

    def build_cache(self, requests, person_file):
        """ Build an account_id to disk cache for active students. """
        for row in requests:
            account_id = row['entity_id']
            account = self.get_account(account_id)
            if not account:
                logger.warning("no account id=%s", repr(account_id))
                self.ignore_accounts.add(account_id)
                continue
            fnr = _get_owner_fnr(account)
            if not fnr:
                # TODO: Move awau from using fnr as a *primary key* when
                # processing students
                logger.warning("No fnr (primary key) for account %s (%d)",
                               account.account_name, account.entity_id)
                self.ignore_accounts.add(account_id)
                continue
            self._fnr_to_accounts.setdefault(fnr, set()).add(account_id)

        # Find disks
        self._autostud.start_student_callbacks(
            person_file,
            self._calc_disk_callback,
        )

    def _get_profile(self, person_info, account):
        """ Get student profile using a given account. """
        memberships = _get_memberships(account)
        try:
            profile = self._autostud.get_profile(person_info,
                                                 member_groups=memberships)
            self._autostud._logger.debug(profile.matcher.debug_dump())
        except AutostudError as msg:
            logger.debug("no profile for id=%d - %s", account.entity_id, msg)
            profile = None
        return profile

    def _calc_disk_callback(self, person_info):
        """
        Callback for AutoStud.

        This callback runs for every active student according to the given
        input file, and finds a disk for any pending account move requests.

        The callback has three outcomes:

        1. A student account is already on an appropriate disk (don't move)
        2. A new disk is found for the given account (move to target disk)
        3. No appropriate disk can be found (move to default disk)

        :param dict person_info: person/student data from AutoStud
        """
        fnr = "%06d%05d" % (int(person_info['fodselsdato']),
                            int(person_info['personnr']))

        if fnr not in self._fnr_to_accounts:
            # no request for this person
            return

        for account_id in self._fnr_to_accounts[fnr]:
            account = self.get_account(account_id)
            logger.debug("Finding disk for account %s (%d)",
                         account.account_name, account.entity_id)
            profile = self._get_profile(person_info, account)
            if profile is None:
                logger.warning("No profile for account %s (%d)",
                               account.account_name, account.entity_id)
                continue

            try:
                disk_t = self._get_disk(account, profile)
            except _InvalidRequest as e:
                logger.info("No disk for account %s (%d): %s",
                            account.account_name, account.entity_id, e)
                # determine_disks decided that this move shouldn't happen - the
                # homedir is already on the correct disk.
                # TODO: Prevent further processing of request_id
                self.ignore_accounts.add(account_id)
                continue

            if not disk_t:
                logger.warning("No student disk for account %s (%d)",
                               account.account_name, account.entity_id)
                continue

            logger.debug("Found disk id=%d for account %s (%d)",
                         disk_t[-1], account.account_name, account.entity_id)
            self.account_to_disk[account_id] = disk_t

            # update quota according to profile
            homedir_id, new_disk = disk_t
            if self._autostud.disk_tool.using_disk_kvote and homedir_id:
                self.disk_quotas[homedir_id] = profile.get_disk_kvote(new_disk)

    def _get_disk(self, account, profile):
        """ Find homedir disks for a given account and profile. """
        profile_spreads = set(int(s) for s in profile.get_spreads())
        disk_spreads = set(int(s) for s in profile.get_disk_spreads())
        valid_spreads = disk_spreads & profile_spreads
        if self.disk_spread not in valid_spreads:
            logger.warning("Ignoring account %s (%d), no %s spread in profile",
                           account.account_name, account.entity_id,
                           self.disk_spread)
            return

        try:
            ah = account.get_home(self.disk_spread)
            homedir_id = ah['homedir_id']
            current_disk_id = ah['disk_id']
        except Errors.NotFoundError:
            raise _InvalidRequest("no home")

        if self._autostud.disk_tool.get_diskdef_by_diskid(current_disk_id):
            # TODO: Couldn't it be a _different_ student disk pool?
            raise _InvalidRequest("already on student disk")

        try:
            new_disk_id = profile.get_disk(self.disk_spread, current_disk_id,
                                           do_check_move_ok=False)
        except AutostudError as msg:
            logger.warning("Unable to find disk for account %s (%d) - %s",
                           account.account_name, account.entity_id, msg)
            return

        if new_disk_id == current_disk_id:
            # Don't think this actually *can* happen, as the
            # *current_disk_id* would have to be a student disk...
            raise _InvalidRequest("already on target disk")

        return homedir_id, new_disk_id


class MoveStudentProcessor(object):

    def __init__(self, db, co, autostud, disk_spread=None):
        """
        Process move student requests.

        :param db:
        :param co:
        :param autostud: A configured AutoStud.AutoStud object
        :param default_spread: default homedir/disk spread
        :param bool dryrun:
        """
        self.db = db
        self.co = co
        self.gr = Factory.get("Group")(db)
        self.br = BofhdRequests(db, co)
        self.disk_cache = DiskCache(db, autostud, disk_spread)

    @property
    def default_spread(self):
        return self.disk_cache.disk_spread

    def _list_requests(self):
        """ list all move student requests """
        return list(self.br.get_requests(operation=self.co.bofh_move_student))

    def _delete_request(self, request_id):
        """ remove request by id """
        self.br.delete_request(request_id=int(request_id))
        logger.info("Removed request id=%s", repr(request_id))

    def _add_request(self, operator, account_id, disk_id, disk_spread):
        """ add a new move request """
        req_id = self.br.add_request(
            operator=int(operator),
            when=self.br.batch_time,
            op_code=int(self.co.bofh_move_user),
            entity_id=int(account_id),
            destination_id=int(disk_id),
            state_data=int(disk_spread),
        )
        logger.info("Added move request id=%d for account id=%s at %s",
                    req_id, repr(account_id), self.br.batch_time)

        # self._update_quota(profile, new_disk, homedir_id)

    def process_requests(self, person_file):
        """
        Process move student requests.

        :param str person_file:
            A file with all current persons from FS (e.g. merged_persons.xml)
        """
        requests = self._list_requests()
        logger.debug("Found %d requests", len(requests))

        if not requests:
            logger.info("No pending move student requests")
            return

        self.disk_cache.build_cache(requests, person_file)
        self.move_users(requests)

    def _update_quota(self, homedir_id):
        """ Update homedir quota according profile. """
        if homedir_id not in self.disk_cache.disk_quotas:
            return
        quota_db = DiskQuota(self.db)
        try:
            cur_quota = quota_db.get_quota(homedir_id)
        except Errors.NotFoundError:
            cur_quota = None
        quota = self.disk_cache.disk_quotas[homedir_id]
        if (cur_quota is None or cur_quota['quota'] != int(quota)):
            quota_db.set_quota(homedir_id, quota=int(quota))

    def move_users(self, requests):
        default_disk = Factory.get('Disk')(self.db)
        default_disk.find_by_path(cereconf.AUTOSTUD_PENDING_DISK)

        for request in requests:
            request_id = request['request_id']
            operator = request['requestee_id']
            account_id = request['entity_id']
            account = self.disk_cache.get_account(account_id)

            if account is None:
                logger.info("Ignoring move request id=%d - no account id=%d",
                            request_id, account_id)
                self._delete_request(request_id)
                continue

            if account_id in self.disk_cache.ignore_accounts:
                logger.info("Ignoring move request id=%d for account %s (%d)",
                            request_id, account.account_name,
                            account.entity_id)
                self._delete_request(request_id)
                continue

            if account_id in self.disk_cache.account_to_disk:
                disk_t = self.disk_cache.account_to_disk.get(account_id)
                homedir_id, new_disk_id = disk_t
                disk = self.disk_cache.get_disk(new_disk_id)
                self._update_quota(homedir_id)
                self._delete_request(request_id)
                self._add_request(
                    operator=operator,
                    account_id=account_id,
                    disk_id=new_disk_id,
                    disk_spread=self.disk_cache.disk_spread,
                )
                logger.info("Moving account %s (%d) to disk %s (%d)",
                            account.account_name, account.entity_id,
                            disk.path, disk.entity_id)
                continue

            # Default
            self._delete_request(request_id)
            self._add_request(
                operator=operator,
                account_id=account_id,
                disk_id=default_disk.entity_id,
                disk_spread=self.default_spread,
            )
            logger.info("Moving account %s (%d) to default disk %s (%d)",
                        account.account_name, account.entity_id,
                        default_disk, default_disk.entity_id)


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Translate *move student* to regular *move* requests",
    )
    parser.add_argument(
        "--perspective",
        dest="perspective",
        # Why FS?  Seems wrong for uio?
        default="FS",
        help="Use ou perspective %(metavar)s (default: %(default)s)",
        metavar="P",
    )
    parser.add_argument(
        "-d", "--debug",
        action="store_true",
        default=False,
        help="Enable autostud debug logging",
    )
    required = parser.add_argument_group("Required files")
    required.add_argument(
        "-c", "--config",
        dest="config_file",
        required=True,
        help="Use student import config from %(metavar)s (e.g. studconf.xml)",
        metavar="FILE",
    )
    required.add_argument(
        "--subjects",
        dest="fs_subjects_file",
        required=True,
        help="Use subjects from %(metavar)s (e.g. emner.xml)",
        metavar="FILE",
    )
    required.add_argument(
        "--programs",
        dest="fs_programs_file",
        default=None,
        required=True,
        help="Use study programs from %(metavar)s (e.g. studieprogs.xml)",
        metavar="FILE",
    )
    required.add_argument(
        "--students",
        dest="fs_persons_file",
        default=None,
        required=True,
        help="Process students from %(metavar)s (e.g. merged_persons.xml)",
        metavar="FILE",
    )

    argutils.add_commit_args(parser)
    Cerebrum.logutils.options.install_subparser(parser)
    args = parser.parse_args()

    Cerebrum.logutils.autoconf("daily", args)

    logger.info("start %s", parser.prog)
    logger.debug("args: %s", repr(args))

    db = Factory.get("Database")()
    db.cl_init(change_program=parser.prog)
    const = Factory.get("Constants")(db)

    # args
    perspective = argutils.get_constant(
        db, parser, const.OUPerspective, args.perspective)

    logger.debug("Configuring AutoStud")
    debug_log = logger.getChild("autostud")
    if not args.debug:
        # filter out autostud debug log messages
        debug_log.setLevel(logging.INFO)
    autostud = AutoStud.AutoStud(
        db, debug_log,
        debug=False,
        cfg_file=args.config_file,
        studieprogs_file=args.fs_programs_file,
        emne_info_file=args.fs_subjects_file,
        ou_perspective=perspective,
    )

    logger.debug("Processing move student requests")
    msp = MoveStudentProcessor(
        db, const, autostud,
        disk_spread=const.spread_uio_nis_user,
    )
    msp.process_requests(args.fs_persons_file)

    if args.commit:
        logger.info("Commiting changes")
        db.commit()
    else:
        logger.info("Rolling back changes (dryrun)")
        db.rollback()

    logger.info("done %s", parser.prog)


if __name__ == '__main__':
    main()
