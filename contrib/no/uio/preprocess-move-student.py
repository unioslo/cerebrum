"""
Script to move student user accounts to an appropriate homedir.

This script is just a ``process_bofhd_requets.py`` pre-processor script.  It
looks up disks for *move student* requests and translates them into regular
*move* requests.

*move student* requests are generated by the bofhd commands `user move
student[_immediate] <username>`, and are requests to move a given user homedir
to an appropriate student disk according to the *studconf.xml* config file and
current FS student data.

The only reason this move-action uses bofhd-requests and has its own script, is
to encapsulate all the messy logic required to find a disk for student
accounts, as this requires a series of up-to-date cache files from FS.

Configuration
==============
*studconf.xml*
    Student profile configuration file.  Used along with the *FS import files*
    to select a target disk for *move student* requests.

``cereconf.AUTOSTUD_PENDING_DISK``
    Sets the default disk to use for requests where the account owner does not
    appear to be a student according to *studconf.xml* and FS import files.

TODO
====
Home directory and disk management has some weird issues:

- We don't support moving students to *new* student disks if they are already
  on a student disk - even if the profile and disk pool changes.

- We can't have *two* bofhd requests of the same type for a given entity.  This
  means that we can't support moving two different home directories for
  different spreads at the same time, which seems like an oversight.

Additionally, this is just one of many use-cases where using the `AutoStud`
module feels like pushing a square peg though a round hole - it's not
designed to be used in this way.

History
========
This used to be implemented in ``contrib/no/uio/process_bofhd_requests.py``.

The main functionality was gathered in a MoveStudentProcessor class, and moved
to :mod:`Cerebrum.modules.bofhd_requests` in a major bofhd-requests refactor.

In an attempt to completely isolate the special *move student* request
requirements and complexities, it was moved out of the ``bofhd_requests``
module and back into this script.
"""
