def find_files(dirname, pattern, file_type="file", min_age=0):
    """
    Find a list of matching paths (files or directories) in *dirname*.

    This function implements the file matching from :class:`.DeleteParams` and
    :class:`.ArchiveParams`.

    :param str dirname:
        only return paths in this directory

    :param str pattern:
        only return paths with a basename that matches this regex pattern

    :param str file_type:
        only return matches of this type ("file" or "dir")

    :param int min_age:
        only return matches that hasn't been modified in *min_age* days

    :returns list:
        a list of matching paths in dirname
    """
    if file_type not in ("file", "dir"):
        raise ValueError("invalid file_type: " + repr(file_type))

    name_regex = re.compile(pattern)
    mtime_threshold = time.time() - date_utils.to_seconds(days=int(min_age))
    logger.debug("Searching for %ss in %s matching %s older than %d days",
                 file_type, dirname, name_regex.pattern, min_age)

    # Soft sanity checks - we shouldn't fail hard if e.g. a directory is
    # missing, but let's log an error for follow-up
    if not os.path.isabs(dirname):
        logger.error("not an absolute path - skipping %s", repr(dirname))
        return []
    if not os.path.isdir(dirname):
        logger.error("not a directory - skipping %s", repr(dirname))
        return []

    matches = []
    for name in os.listdir(dirname):
        file_path = os.path.join(dirname, name)
        if file_type == "dir" and not os.path.isdir(file_path):
            continue
        if file_type == "file" and not os.path.isfile(file_path):
            continue
        if not name_regex.match(name):
            continue
        if os.path.getmtime(file_path) >= mtime_threshold:
            continue
        matches.append(file_path)
    logger.info("Found %d %ss in %s with pattern %s older than %s days",
                len(matches), file_type, dirname, name_regex.pattern, min_age)
    return sorted(matches)


class ArchiveName(object):
    """ Helper for naming and identifying archives. """

    def __init__(self, archive_type, archive_dir, source_pattern,
                 replace=True, use_date_suffix=False):
        """
        :param str archive_type:
            Set to "file" when archiving single files, or any other value for
            tarballs.

        :param str archive_dir:
            Path to a directory for archive files

        :param str source_pattern:
            A regex pattern that matches the archive prefix.

            This is typically the pattern that is being fed into `find_files`
            to create this archive.

        :param bool replace:
            If *True*, this may return a path that already exists.  This may
            result in an existing archive being overwritten.

            If set to False, a counter suffix is appended to the file name,
            which should prevent archives from being overwritten in consecutive
            runs.

        :param bool use_date_suffix:
            If *True*, archive filenames will include the current date.
        """
        self.archive_type = archive_type
        self.archive_dir = archive_dir
        self.source_pattern = source_pattern
        self.replace = replace
        self.use_date_suffix = use_date_suffix

    @property
    def fileext(self):
        """ Archive file extension. """
        return ".gz" if self.archive_type == "file" else ".tar.gz"

    @property
    def suffix(self):
        if self.use_date_suffix:
            return datetime.date.today().strftime("-%Y-%m-%d")
        return ""

    def get_archive_name(self, prefix):
        """
        Get path and filename for a new archive.

        :param str prefix:
            Prefix for the archive to create.  This is typically the the
            basename of the file or directory name that we are archiving.
        """
        file_fmt = "{prefix}{suffix}{fileext}"
        file_fmt_count = "{prefix}{suffix}--{count}{fileext}"
        suffix = self.suffix
        for count in range(1000):
            filename = os.path.join(
                self.archive_dir,
                file_fmt.format(prefix=prefix, suffix=suffix,
                                count=count, fileext=self.fileext),
            )
            if os.path.exists(filename) and not self.replace:
                # A file with the same name exists - try again, but with a
                # counter
                file_fmt = file_fmt_count
                continue
            return filename
        raise RuntimeError("No archive name available in %s for %s"
                           % (self.archive_dir, prefix))

    def get_archive_pattern(self):
        """ Get a regex pattern for matching archive files. """
        # Our file should start with our expected base pattern ...
        #
        # Note that this bit will fail if we explicitly want to match files
        # ending in a properly escaped, literal $.  Hmm, don't want a full
        # regex tokenizer here...
        parts = [self.source_pattern.rstrip("$")]
        if self.use_date_suffix:
            # ... followed by a ISO8601 calendar date
            parts.append(r"-\d{4}-\d{2}-\d{2}")
        if not self.replace:
            # ... followed by an optional counter value
            parts.append(r"(?:--\d+)?")
        # ... ending in the expected file extension
        parts = parts + [re.escape(self.fileext), "$"]
        return "".join(parts)

    @classmethod
    def from_config(cls, config):
        """ Create an ArchiveName scheme from a set of ArchiveParams.  """
        archive_dir = config.archive_dir or config.dirname
        source_pattern = (
            re.escape(config.archive_combo)
            if config.archive_combo
            else config.pattern.rstrip("$")
        )
        return cls(
            archive_type=(
                "file"
                if (config.file_type == "file" and not config.archive_combo)
                else "tar"
            ),
            archive_dir=archive_dir,
            source_pattern=source_pattern,
            replace=config.archive_replace,
            # Our "combined" archives gets an added date suffix
            use_date_suffix=bool(config.archive_combo),
        )


#
# We reduce the compression level from the Python default (9) to the GNU gzip
# default (6).  This makes our compression speed perform ~ as good as calling
# subprocess.run(["gzip", ...]).
DEFAULT_COMPRESSION_LEVEL = 6

# Changing/setting the buffer size should prevent copyfileobj from using a lot
# of memory, and seems to help compression speed marginally.
#
# The default tarfile bufsize is 512 * 20, so increasing that should reduce
# the number of write syscalls, maybe?
DEFAULT_BUFFER_SIZE = 512 * 10000


class FileActions(reprutils.ReprEvalMixin):
    """
    Handler for doing basic file processing.

    This class can compress files, remove files, and update file attributes.
    It has a dryrun mode that prevents any changes to the file system.
    """
    repr_module = False
    repr_kwargs = ("dryrun",)

    def __init__(self, dryrun=True):
        self.dryrun = dryrun

    def _gzip(self, src, dst,
              compresslevel=DEFAULT_COMPRESSION_LEVEL,
              bufsize=DEFAULT_BUFFER_SIZE):
        logger.debug("%s._gzip(%s, %s)", repr(self), repr(src), repr(dst))
        if src == dst:
            raise ValueError("same gzip src and dst: " + repr(src))
        if not os.path.isfile(src):
            raise ValueError("no file: " + repr(src))
        if os.path.exists(dst):
            logger.warning("will replace existing %s", repr(dst))
        if self.dryrun:
            return
        with io.open(src, mode="rb") as f_in:
            with gzip.open(dst, mode="wb",
                           compresslevel=compresslevel) as f_out:
                shutil.copyfileobj(f_in, f_out, bufsize)

    def _copystat(self, src, dst):
        logger.debug("%s._copystat(%s, %s)", repr(self), repr(src), repr(dst))
        if self.dryrun:
            return
        shutil.copystat(src, dst)

    def unlink(self, path):
        """ Delete a single file. """
        logger.info("%s.unlink(%s)", repr(self), repr(path))
        if not os.path.isfile(path):
            raise ValueError("not a file: " + repr(path))
        if self.dryrun:
            return
        os.unlink(path)

    def gzip_file(self, src, dst, keep_original=False,
                  preserve_attrs=True):
        """
        Compress (gzip) a single file.

        :param str src:
            path to the file to compress

        :param str dst:
            path to the archive file (.gz)

        :param bool keep_original:
            Do not delete the original after successful compression

        :param bool preserve_attrs:
            Copy attributes (copystat) from original
        """
        src = os.path.abspath(src)
        dst = os.path.abspath(dst)
        logger.info(
            "%s.gzip_file(%s, %s, keep_original=%s, preserve_attrs=%s)",
            repr(self), repr(src), repr(dst), repr(keep_original),
            repr(preserve_attrs))
        self._gzip(src, dst)
        if preserve_attrs:
            self._copystat(src, dst)
        if not keep_original:
            self.unlink(src)

    def set_mtime(self, path, timestamp):
        """
        Set mtime to the given timestamp.

        Also updates atime if the given mtime is more recent.

        :param str path:
            path to the file or directory to update

        :param float timestamp:
            The timestamp to set
        """
        new_mtime = float(timestamp)
        if not os.path.exists(path):
            raise ValueError("no path: " + repr(path))
        logger.info("%s.set_mtime(%s, %s)",
                    repr(self), repr(path), repr(new_mtime))
        old_atime = os.path.getatime(path)
        new_atime = old_atime if old_atime > new_mtime else new_mtime
        times = (new_atime, new_mtime)
        if self.dryrun:
            return
        os.utime(path, times)

    def _tar_gzip(self, src, dst,
                  compresslevel=DEFAULT_COMPRESSION_LEVEL,
                  bufsize=DEFAULT_BUFFER_SIZE):
        if src == dst:
            raise ValueError("same gzip src and dst: " + repr(src))
        if not os.path.isdir(src):
            raise ValueError("src directory missing: " + repr(src))
        # if os.path.exists(dst):
        #     raise ValueError("dst gzip already exists: " + repr(dst))
        logger.debug("%s._tar_gzip(%s, %s)", repr(self), repr(src), repr(dst))
        arcname = os.path.basename(src)
        if self.dryrun:
            return
        with tarfile.open(name=dst, mode="w:gz",
                          compresslevel=compresslevel,
                          bufsize=bufsize) as tf:
            tf.add(src, arcname=arcname, recursive=True)

    def rmtree(self, path):
        """ Recursively delete a directory tree. """
        logger.info("%s.rmtree(%s)", repr(self), repr(path))
        if not os.path.isdir(path):
            raise ValueError("not a directory: " + repr(path))
        if self.dryrun:
            return
        shutil.rmtree(path)

    def gzip_dir(self, src, dst, keep_original=False):
        """
        Compress a single directory tree into a gzipped tarball.

        :param str src:
            path to the directory to compress

        :param str dst:
            path to the archive file (.tar.gz)

        :param bool keep_original:
            Do not delete the original after successful compression
        """
        src = os.path.abspath(src)
        dst = os.path.abspath(dst)
        logger.info("%s.gzip_dir(%s, %s, keep_original=%s)",
                    repr(self), repr(src), repr(dst),
                    repr(keep_original))

        self._tar_gzip(src, dst)
        if not keep_original:
            self.rmtree(src)

    def _tar_gzip_entries(self, src, dst, entries,
                          compresslevel=DEFAULT_COMPRESSION_LEVEL,
                          bufsize=DEFAULT_BUFFER_SIZE):
        if src == dst:
            raise ValueError("same gzip src and dst: " + repr(src))
        if not os.path.isdir(src):
            raise ValueError("src directory missing: " + repr(src))

        sanitized = []
        for arcname in entries:
            full_path = os.path.join(src, arcname)
            if not os.path.exists(full_path):
                raise ValueError("item missing: %s" + repr(full_path))
            sanitized.append((full_path, arcname))

        logger.debug("%s._tar_gzip_entries(%s, %s, %s)", repr(self), repr(src),
                     repr(dst), repr(entries))
        retval = [p for p, _ in sanitized]

        if self.dryrun:
            return retval

        with tarfile.open(name=dst, mode="w:gz",
                          compresslevel=compresslevel,
                          bufsize=bufsize) as tf:
            for full_path, arcname in sanitized:
                tf.add(full_path, arcname=arcname, recursive=True)
        return retval

    def gzip_list(self, src, dst, entries, keep_original=False):
        """
        Compress a list of files from a directory tree into a tarball.

        :param str src:
            path to the directory to compress

        :param str dst:
            path to the archive file (.tar.gz)

        :param list entries:
            A list of files and directories within *src* to archive.
            Each item must be relative to *src*.

        :param bool keep_original:
            Do not delete the original after successful compression
        """
        src = os.path.abspath(src)
        dst = os.path.abspath(dst)
        logger.info("%s.gzip_list(%s, %s, %s, keep_original=%s)",
                    repr(self), repr(src), repr(dst),
                    repr(entries), repr(keep_original))

        added = self._tar_gzip_entries(src, dst, entries)
        if not keep_original:
            for full_path in added:
                if os.path.isdir(full_path):
                    self.rmtree(full_path)
                else:
                    self.unlink(full_path)


class Archiver(object):
    """ Helper for log file archiving and cleanup. """

    def __init__(self, dryrun):
        self._exec = FileActions(dryrun)

    def _delete(self, path):
        if os.path.isfile(path):
            self._exec.unlink(path)
        elif os.path.isdir(path):
            self._exec.rmtree(path)
        else:
            raise ValueError("not a file or directory: " + repr(path))

    def delete_matches(self, dirname, pattern, file_type="file", min_age=0):
        """
        Delete all matching paths in *dirname*.

        Arguments are the same as :func:`.find_files`.
        """
        # Find files matching pattern and age threashold
        for name in find_files(dirname, pattern, file_type=file_type,
                               min_age=min_age):
            try:
                fullpath = os.path.join(dirname, name)
                self._delete(fullpath)
            except Exception:
                logger.error("Unable to delete %s",
                             repr(fullpath), exc_info=True)

    def archive_file(self, filename, archive, keep_originals=False):
        """ Archive a single file. """
        logger.info("Archiving file %s -> %s", repr(filename), repr(archive))
        self._exec.gzip_file(filename, archive, keep_original=keep_originals,
                             preserve_attrs=True)

    def archive_dir(self, dirname, archive, keep_originals=False):
        """ Archive a single directory. """
        timestamp = int(os.path.getmtime(dirname))
        logger.info("Archiving dir %s -> %s", repr(dirname), repr(archive))
        self._exec.gzip_dir(dirname, archive, keep_originals)
        if timestamp is not None:
            self._exec.set_mtime(archive, timestamp)

    def archive_list(self, dirname, archive, entries, keep_original):
        """ Archive selected entries within a single directory. """
        # special behaviour - one archive with all entries
        #
        # This expects that all items are abspath(s) within dirname
        relpaths = [os.path.relpath(i, dirname) for i in entries]
        self._exec.gzip_list(dirname, archive, relpaths, keep_original)


def delete_files(config, dryrun):
    """
    Process a single delete action.

    Deletes files according to a :class:`.DeleteParams` specification.

    :param DeleteParams config:
        A configuration object that specifies which files to delete.

    :param bool dryrun:
        Optionally run in dryrun mode, which prevents any files from being
        deleted.
    """
    archiver = Archiver(dryrun)
    logger.info("Deleting %ss in %s matching %s older than %d days",
                config.file_type, config.dirname, config.pattern,
                config.delete_age)
    archiver.delete_matches(
        dirname=config.dirname,
        pattern=config.pattern,
        file_type=config.file_type,
        min_age=config.delete_age,
    )


def archive_files(config, dryrun):
    """
    Process a single archive action.

    Archives files or directories according to a :class:`.ArchiveParams`
    specification.

    :param ArchiveParams config:
        A configuration object that specifies what to archive.

    :param bool dryrun:
        Optionally run in dryrun mode, which prevents new archives from being
        created, and originals from being deleted.
    """
    archiver = Archiver(dryrun)
    dirname = config.dirname
    name_scheme = ArchiveName.from_config(config)

    if config.delete_age > 0:
        logger.info("Archive cleanup for %s", dirname)
        # Delete any files/directories that are too old to be archived.  This
        # shouldn't normally happen, but can occur e.g. when adding a new set
        # of archiving params, or ajusting a `delete_age` setting down.
        archiver.delete_matches(
            dirname=config.dirname,
            pattern=config.pattern,
            file_type=config.file_type,
            min_age=config.delete_age,
        )
        # Delete any archives that are too old.
        archiver.delete_matches(
            dirname=name_scheme.archive_dir,
            pattern=name_scheme.get_archive_pattern(),
            file_type="file",
            min_age=config.delete_age,
        )

    logger.info("Archiving %ss in %s", config.file_type, dirname)
    items = find_files(dirname, config.pattern, config.file_type,
                       config.archive_age)
    if not items:
        logger.info("Nothing to archive in %s", dirname)
        return

    if config.archive_combo:
        # special behaviour - one archive with all matching entries
        archive_name = name_scheme.get_archive_name(config.archive_combo)
        archiver.archive_list(dirname, archive_name, items,
                              config.keep_originals)
        return

    if config.file_type == "dir":
        for path in items:
            archive_name = name_scheme.get_archive_name(os.path.basename(path))
            archiver.archive_dir(path, archive_name,
                                 keep_originals=config.keep_originals)
        return

    if config.file_type == "file":
        for path in items:
            archive_name = name_scheme.get_archive_name(os.path.basename(path))
            archiver.archive_file(path, archive_name,
                                  keep_originals=config.keep_originals)
        return

    # Shouldn't happen
    raise NotImplementedError("No support for file_type: "
                              + repr(config.file_type))


def main(argv=None):
    """Main script runtime. Parses arguments. Starts tasks."""
    parser = argparse.ArgumentParser(
        description="Archive and delete files according to config",
        epilog=textwrap.dedent(
            """
            This script reads archiving (ARCHIVE_FILES) and cleanup
            (DELETE_FILES) instructions from the importable config module
            `file_clean_conf` (or another python file given as --config).

            The script should normally run daily in order to archive and clean
            up log files, caches, and similar temporary files.
            """
        ).strip(),
    )
    parser.add_argument(
        "--config",
        dest='config',
        required=(file_clean_conf is None),
        help='Read config from %(metavar)s (default: `file_clean_conf`)',
        metavar="<file>",
    )
    parser.add_argument(
        "--archive",
        default=False,
        action="store_true",
        dest="archive_mode",
        help="Run archiving actions",
    )
    parser.add_argument(
        "--delete",
        default=False,
        action="store_true",
        dest="delete_mode",
        help="Run delete actions",
    )
    parser.add_argument(
        "--show-params",
        default=False,
        action="store_true",
        help="Show all delete and archive actions",
    )
    commit_group = parser.add_argument_group(
        "dryrun",
        """
        By default this script only runs in dryrun mode, which won't actually
        archive or delete anything.
        """,
    )
    argutils.add_commit_args(commit_group,
                             commit_desc="Actually archive and/or delete")
    Cerebrum.logutils.options.install_subparser(parser)

    args = parser.parse_args(argv)
    Cerebrum.logutils.autoconf("cronjob", args)
    if not any((args.archive_mode, args.delete_mode, args.show_params)):
        parser.error("no action given")

    logger.info("Start %s", parser.prog)
    logger.debug("args: %s", repr(args))

    dryrun = not args.commit
    logger.info("Archiving: %s", args.archive_mode)
    logger.info("Deleting: %s", args.delete_mode)
    logger.info("Dryrun: %s", dryrun)

    # Read processing actions from file or default config module:
    if args.config:
        config = load_source("file-clean-conf", args.config)
    else:
        config = file_clean_conf
    archive_actions = get_archive_config(config)
    delete_actions = get_delete_config(config)

    if args.show_params:
        print("Delete actions:")
        print(json.dumps([a.dump_dict() for a in delete_actions],
                         sort_keys=True, indent=2))
        print()
        print("Archive actions:")
        print(json.dumps([a.dump_dict() for a in archive_actions],
                         sort_keys=True, indent=2))

    if args.delete_mode:
        if not delete_actions:
            logger.error("Delete mode requested, but nothing to delete")
        for delete_spec in delete_actions:
            delete_files(delete_spec, dryrun)

    if args.archive_mode:
        if not archive_actions:
            logger.error("Archive mode requested, but nothing to archive")
        for archive_spec in archive_actions:
            archive_files(archive_spec, dryrun)

    logger.info("Done %s", parser.prog)


if __name__ == '__main__':
    main()
