r"""
Configurable script for deleting and archiving files.

The script can run in archive mode, delete mode, or both:

Archive mode
    Compress files and directories of a given age and naming pattern.  Archives
    can also be deleted after a given time.  This is useful for keeping certain
    files around for some time.  Often used to compress large, time-rotated log
    files.

    This mode uses ``ArchiveParams`` from ``file_clean_conf.ARCHIVE_FILES``.

Delete mode
    Delete files and directories of a given age and naming pattern.  This is
    useful for files that has no need for compression, and typically isn't kept
    around for too long.  Typical use case is to remove letters generated by
    the FS import.

    This mode uses ``DeleteParams`` from ``file_clean_conf.DELETE_FILES``.

History
-------
This script is a rewrite of ``contrib/file_clean.py``.  It uses the same config
file, but with a slightly different, incompatible config structure.
"""
