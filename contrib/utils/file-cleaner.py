class DeleteParams(configuration.Configuration):
    """ Parameters for finding and deleting files or folders.  """

    dirname = configuration.ConfigDescriptor(
        settings.String,
        minlen=1,
        doc="Process items (files or directories) from this path.",
    )
    pattern = configuration.ConfigDescriptor(
        settings.String,
        minlen=1,
        doc="Only process items matching this filename (basename) pattern",
    )
    file_type = configuration.ConfigDescriptor(
        settings.Choice,
        choices=set(("file", "dir")),
        default="file",
        doc="Only process items matching this type",
    )
    delete_age = configuration.ConfigDescriptor(
        settings.Integer,
        minval=0,
        default=0,
        doc="Only delete items older than this (in days)",
    )

    @classmethod
    def from_dict(cls, d):
        """ Create config from dict and validate. """
        config = cls(d)
        config.validate()
        return config


class ArchiveParams(DeleteParams):
    """ Parameters for finding and archiving files or folders.  """

    archive_dir = configuration.ConfigDescriptor(
        settings.String,
        default=None,
        doc=textwrap.dedent(
            """
            Place archives in this diretctory.  If unset, archives are placed
            in the source *dirname*.
            """
        ).strip(),
    )
    archive_age = configuration.ConfigDescriptor(
        settings.Integer,
        minval=0,
        default=0,
        doc="Only archive matching items older than this (in days)",
    )
    archive_replace = configuration.ConfigDescriptor(
        settings.Boolean,
        default=False,
        doc=textwrap.dedent(
            """
            Replace existing archives.

            If the same archive gets built twice, the existing archive will be
            replaced.  This can happen e.g. when running with *keep_originals*
            set and archiving the same file twice.

            If unset, numbered copies will be created, e.g.: foo.gz, foo--1.gz
            """
        ).strip(),
    )
    archive_combo = configuration.ConfigDescriptor(
        settings.String,
        default=None,
        doc=textwrap.dedent(
            """
            Create a single archive with all mathing items.

            If set, this will put *all* matching items (files or directories)
            into a single, combined archive file with this prefix.

            If unset, each matching item will get its own archive, with the
            archive named from its input item.
            """
        ).strip(),
    )
    keep_originals = configuration.ConfigDescriptor(
        settings.Boolean,
        default=False,
        doc=(
            "If set to True, keep items after archiving"
            " (default: delete items after archiving)",
        ),
    )


def _autoload_config_list(config_type, config_module, attr_name):
    logger.info("Using settings from %s.%s", repr(config_module), attr_name)
    return [config_type.from_dict(d)
            for d in getattr(config_module, attr_name, [])]


def get_delete_config(config):
    """ Sanity check and normalize file_clean_conf.ARCHIVE_FILES """
    return _autoload_config_list(DeleteParams, config, "DELETE_FILES")


def get_archive_config(config):
    """ Sanity check and normalize file_clean_conf.ARCHIVE_FILES """
    return _autoload_config_list(ArchiveParams, config, "ARCHIVE_FILES")


